import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
const page = await browser.newPage({acceptDownloads:true, viewport:{width:390,height:844}});
const errors=[];
page.on('pageerror', e=>errors.push(String(e)));
const check=(ok, label)=>{if(!ok)throw new Error(label); console.log('PASS',label)};
try{
 await page.goto(pathToFileURL(resolve('index.html')).href);
 await page.waitForTimeout(300);
 check(await page.locator('#welcome').isVisible(), 'Welcome panel visible');
 await page.locator('[data-tab="challenge"]').click();
 check(await page.locator('#challenge').isVisible(),'Challenge navigation');
 await page.locator('[data-choice="supplies"]').check();
 check((await page.locator('#challengeMetrics').innerText()).includes('$9,000'),'Scenario calculations');
 await page.locator('[data-tab="forecast"]').click();
 check(await page.locator('#forecast').isVisible(),'Forecast navigation');
 check((await page.locator('#fcChart svg').count())>0,'Forecast chart renders');
 await page.locator('#fcInflation').fill('7');
 check((await page.locator('#fcMetrics').innerText()).length>20,'Forecast recalculates');
 let dl=page.waitForEvent('download');
 await page.locator('#fcExport').click();
 check((await dl).suggestedFilename().endsWith('.csv'),'Forecast CSV download');
 await page.locator('#faSnapshot').click();
 check(await page.locator('#faSelect option').count()>0,'Forecast snapshot saved');
 await page.locator('#fcCutoff').selectOption('10');
 await page.locator('#faRefresh').click();
 check((await page.locator('#faMetrics').innerText()).includes('MAE'),'Accuracy KPI display');
 await page.locator('[data-tab="reports"]').click();
 check(await page.locator('#reports').isVisible(),'Reports navigation');
 dl=page.waitForEvent('download');
 await page.locator('#reportPdf').click();
 check((await dl).suggestedFilename().endsWith('.pdf'),'PDF download generated');
 await page.locator('#reportDataset').selectOption('budget');
 dl=page.waitForEvent('download');
 await page.locator('#reportCsv').click();
 check((await dl).suggestedFilename().endsWith('.csv'),'Reporting CSV download');
 check(errors.length===0,'No uncaught page errors: '+errors.join(' | '));
 console.log('All browser smoke tests passed');
}finally{await browser.close()}
